    #[test]
    fn installer_is_idempotent_and_requires_force() {
        let (_ctx, base) = context("install");
        let path = base.join("nested/codex-switch");
        assert!(install_bash(&path, false).unwrap());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), bash_script());
        assert!(!install_bash(&path, false).unwrap());
        std::fs::write(&path, "foreign\n").unwrap();
        assert!(install_bash(&path, false).is_err());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "foreign\n");
        assert!(install_bash(&path, true).unwrap());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), bash_script());
        std::fs::remove_dir_all(base).unwrap();
    }

    #[test]
    fn installer_reports_invalid_paths_and_never_races_no_clobber() {
        let (_ctx, base) = context("errors");
        let blocker = base.join("blocker");
        std::fs::create_dir_all(&base).unwrap();
        std::fs::write(&blocker, "x").unwrap();
        assert!(install_bash(&blocker.join("codex-switch"), false).is_err());
        assert!(install_bash(Path::new(""), false).is_err());

        let raced = base.join("raced/codex-switch");
        let raced_for_hook = raced.clone();
        assert!(install_bash_with(&raced, false, || {
            std::fs::write(&raced_for_hook, "created concurrently\n").unwrap();
        })
        .is_err());
        assert_eq!(
            std::fs::read_to_string(&raced).unwrap(),
            "created concurrently\n"
        );
        assert!(bash_script().contains("CODEX_SWITCH_COMPLETE=bash codex-switch"));
        std::fs::remove_dir_all(base).unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn installer_preserves_symlinks_without_force_and_replaces_with_force() {
        use std::os::unix::fs::symlink;

        let (_ctx, base) = context("symlink");
        std::fs::create_dir_all(&base).unwrap();
        let target = base.join("target");
        let path = base.join("codex-switch");
        std::fs::write(&target, "foreign\n").unwrap();
        symlink(&target, &path).unwrap();
        assert!(install_bash(&path, false).is_err());
        assert!(std::fs::symlink_metadata(&path)
            .unwrap()
            .file_type()
            .is_symlink());
        assert!(install_bash(&path, true).unwrap());
        assert!(!std::fs::symlink_metadata(&path)
            .unwrap()
            .file_type()
            .is_symlink());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), bash_script());

        std::fs::remove_file(&path).unwrap();
        symlink(base.join("missing"), &path).unwrap();
        assert!(install_bash(&path, false).is_err());
        assert!(install_bash(&path, true).unwrap());
        std::fs::remove_dir_all(base).unwrap();
    }
