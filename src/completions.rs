    #[test]
    fn resolves_standard_completion_paths() {
        let expected = Path::new("/tmp/home/.local/share/bash-completion/completions/codex-switch");
        assert_eq!(
            completion_path(Some(OsStr::new("/tmp/data")), None).unwrap(),
            Path::new("/tmp/data/bash-completion/completions/codex-switch")
        );
        assert_eq!(
            completion_path(Some(OsStr::new("")), Some(OsStr::new("/tmp/home"))).unwrap(),
            expected
        );
        assert_eq!(
            completion_path(Some(OsStr::new("relative")), Some(OsStr::new("/tmp/home"))).unwrap(),
            expected
        );
        assert!(completion_path(Some(OsStr::new("relative")), None).is_err());
        assert!(completion_path(None, Some(OsStr::new("relative"))).is_err());
        assert!(completion_path(None, Some(OsStr::new(""))).is_err());
        assert!(completion_path(None, None).is_err());
    }

